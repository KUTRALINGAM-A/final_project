        (axes[0,1], 'Forward Velocity Error (Kp=2, Kd=0.5)', 
         'Error (m/s)', C['vx'], data['error_vx']),
        (axes[1,0], 'Lateral Velocity Error (Kp=2, Kd=0.5)', 
         'Error (m/s)', C['vy'], data['error_vy']),
        (axes[1,1], 'Roll Error (Kp=0.5, Kd=0.1)', 
         'Error (rad)', C['roll'], data['error_roll']),
