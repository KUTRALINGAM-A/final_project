def load_csv(csv_path):
    """
    Load the PID log CSV file into numpy arrays.
    Returns a dictionary of column_name -> numpy array.
    """
    if not os.path.exists(csv_path):
        print(f"\n❌ ERROR: CSV file not found at:\n   {csv_path}")
        print(f"\n📋 To generate this file:")
        print(f"   1. Open Webots and load the crazyflie.wbt world")
        print(f"   2. Run the simulation (the controller will log data)")
        print(f"   3. The CSV file will be created automatically")
        print(f"   4. Then run this script again")
        sys.exit(1)
    
    # Read header
    with open(csv_path, 'r') as f:
        reader = csv.reader(f)
        header = next(reader)
        rows = list(reader)
    
    if len(rows) == 0:
        print(f"❌ CSV file is empty — run the Webots simulation first!")
        sys.exit(1)
    
    print(f"✅ Loaded {len(rows)} data points from: {csv_path}")
    
    # Parse into dict
    data = {}
    for col_idx, col_name in enumerate(header):
        if col_name == 'mode':
            data[col_name] = [row[col_idx] for row in rows]
        else:
            data[col_name] = np.array([float(row[col_idx]) for row in rows])
    
    return data


def find_settling_time(time_arr, error_arr, threshold_pct=0.02):
    """
    Find the settling time: first time the error stays within ±threshold_pct 
    of the initial error magnitude, and remains there for ≥50 samples.
    """
    initial = np.max(np.abs(error_arr[:max(1, len(error_arr)//20)]))
    if initial < 1e-8:
        return None
    
    thr = threshold_pct * initial
    for idx in range(len(error_arr)):
        remain = min(50, len(error_arr) - idx)
        if remain >= 20 and np.all(np.abs(error_arr[idx:idx+remain]) < thr):
            return time_arr[idx]
    return None


def plot_error_channel(ax, time, error, title, ylabel, color, 
                       annotate_settling=True):
    """Plot a single error channel with consistent styling."""
    ax.plot(time, error, color=color, linewidth=1.5, label='Error')
    ax.axhline(y=0, color='gray', linestyle='--', linewidth=0.8, alpha=0.6)
    ax.fill_between(time, 0, error, alpha=0.10, color=color)
    ax.set_title(title, fontsize=13, fontweight='bold', pad=8)
    ax.set_xlabel('Time (s)', fontsize=11)
    ax.set_ylabel(ylabel, fontsize=11)
    ax.grid(True, alpha=0.3, linestyle='-')
    ax.spines['top'].set_visible(False)
    ax.spines['right'].set_visible(False)
    ax.tick_params(labelsize=10)
    
    # Settling time annotation
    if annotate_settling:
        ts = find_settling_time(time, error)
        if ts is not None and ts > 0.05:
            ax.axvline(x=ts, color=color, linestyle=':', linewidth=1.2, alpha=0.7)
            y_range = np.max(error) - np.min(error)
            y_pos = np.mean(error[:max(1,len(error)//10)]) * 0.4
            ax.annotate(f'Ts ≈ {ts:.2f}s', xy=(ts, 0),
                      xytext=(ts + (time[-1]-time[0])*0.05, y_pos),
                      fontsize=9, fontweight='bold', color=color,
                      arrowprops=dict(arrowstyle='->', color=color, lw=1.2),
                      bbox=dict(boxstyle='round,pad=0.3', facecolor='white',
                               edgecolor=color, alpha=0.8))


def add_mode_background(ax, time, modes):
    """Add colored background bands showing flight mode (flying/wall_following/landing)."""
    mode_colors = {
        'flying': '#E8F5E9',          # Light green
        'wall_following': '#FFF3E0',   # Light orange
        'landing': '#E3F2FD',          # Light blue
    }
    
    if len(modes) == 0:
        return
    
    current_mode = modes[0]
    start_idx = 0
    
    for i in range(1, len(modes)):
        if modes[i] != current_mode or i == len(modes) - 1:
            end_idx = i
            if current_mode in mode_colors:
                ax.axvspan(time[start_idx], time[min(end_idx, len(time)-1)],
                          alpha=0.15, color=mode_colors[current_mode], zorder=0)
            current_mode = modes[i]
            start_idx = i


